def kill_tree(proc: subprocess.Popen) -> None:
    """Stop a program and everything it started."""
    if proc.poll() is not None:
        return
    try:
        if IS_WINDOWS:
            subprocess.run(["taskkill", "/F", "/T", "/PID", str(proc.pid)], capture_output=True,
                           creationflags=CREATE_NO_WINDOW, timeout=10)
        else:
            os.killpg(os.getpgid(proc.pid), signal.SIGKILL)
    except (OSError, subprocess.SubprocessError):
        pass
    try:
        proc.kill()
    except OSError:
        pass


class ProcessControl:
    """Lets another thread type into, or stop, the program that is running."""

    def __init__(self) -> None:
        self.proc: Optional[subprocess.Popen] = None
        self.lock = threading.Lock()
        self.stopped = False

    def write(self, text: str) -> None:
        with self.lock:
            proc = self.proc
            if proc is None or proc.poll() is not None or proc.stdin is None:
                raise BuildError("No program is running that can receive input.")
            try:
                proc.stdin.write(text.encode("utf-8"))
                proc.stdin.flush()
            except (BrokenPipeError, OSError):
                raise BuildError("The program is no longer reading input.")

    def kill(self) -> None:
        self.stopped = True
        proc = self.proc
        if proc is not None:
            kill_tree(proc)


Emit = Callable[..., None]


def _exec(step: Step, root: pathlib.Path, env: Dict[str, str], emit: Emit,
          control: ProcessControl, timeout: int) -> int:
    kwargs: Dict[str, object] = dict(cwd=str(root), env=env, stdin=subprocess.PIPE,
                                     stdout=subprocess.PIPE, stderr=subprocess.STDOUT, bufsize=0)
    if IS_WINDOWS:
        kwargs["creationflags"] = CREATE_NO_WINDOW | CREATE_NEW_PROCESS_GROUP
    else:
        kwargs["start_new_session"] = True
    try:
        proc = subprocess.Popen(step.args, **kwargs)  # shell=False: arguments are never parsed by a shell
    except FileNotFoundError:
        emit("out", text=f"Cannot start '{step.args[0]}': file not found.\n")
        return 127
    except OSError as exc:
        emit("out", text=f"Cannot start '{step.args[0]}': {exc}\n")
        return 126
    control.proc = proc

    timer: Optional[threading.Timer] = None
    if timeout > 0:
        def on_timeout() -> None:
            emit("out", text=f"\n[stopped: the program ran longer than the {timeout} second limit]\n")
            control.stopped = True
            kill_tree(proc)
        timer = threading.Timer(timeout, on_timeout)
        timer.daemon = True
        timer.start()

    decoder = codecs.getincrementaldecoder("utf-8")(errors="replace")
    total = 0
    try:
        while True:
            chunk = proc.stdout.read(4096)  # type: ignore[union-attr]
            if not chunk:
                break
            total += len(chunk)
            text = decoder.decode(chunk)
            if text:
                emit("out", text=text)
            if total > MAX_OUTPUT_BYTES:
                emit("out", text="\n[stopped: the program printed more than 2 MB of output]\n")
                control.stopped = True
                kill_tree(proc)
                break
        tail = decoder.decode(b"", final=True)
        if tail:
            emit("out", text=tail)
        proc.wait()
    finally:
        if timer:
            timer.cancel()
        try:
            if proc.stdin:
                proc.stdin.close()
        except OSError:
            pass
    return int(proc.returncode if proc.returncode is not None else -1)


def run_plan(plan: Plan, root: pathlib.Path, cfg: Dict[str, object], emit: Emit,
             control: ProcessControl) -> None:
    """Run every step in order. Emits phase / out / exit events. Blocks until done."""
    root = root.resolve()
    env = child_env()
    env.update(plan.env)
    timeout = int(cfg.get("run_timeout", 0) or 0)
    started = time.perf_counter()
    if plan.note:
        emit("note", text=plan.note)
    for step in plan.steps:
        emit("phase", name=step.name, cmd=display_of(step.args, root))
        code = _exec(step, root, env, emit, control, timeout)
        seconds = round(time.perf_counter() - started, 2)
        if control.stopped:
            emit("exit", ok=False, stopped=True, code=code, phase=step.name, seconds=seconds)
            return
        if code != 0:
            emit("exit", ok=False, stopped=False, code=code, phase=step.name, seconds=seconds)
            return
    emit("exit", ok=True, stopped=False, code=0, phase="run", seconds=round(time.perf_counter() - started, 2))


# --------------------------------------------------------------------------- #
# Opening the user's own terminal window (Windows)
# --------------------------------------------------------------------------- #

_BAD_BAT_CHARS = re.compile(r'[%"\r\n!]')


def _bat_quote(arg: str) -> str:
    if _BAD_BAT_CHARS.search(arg):
        raise BuildError("A file name contains a character (% ! or a quote) that cannot be passed "
                         "to an external terminal safely. Rename the file or use the inbuilt terminal.")
    if arg.endswith("\\"):
        arg += "\\"
    return '"' + arg + '"'


def external_script(plan: Plan, root: pathlib.Path) -> str:
    """The text of the .bat file that compiles and runs the plan in a visible console."""
    root = root.resolve()
    title = re.sub(r'[&|<>^%"!]', "", plan.rel)
    lines = ["@echo off", "chcp 65001 >nul", f"cd /d {_bat_quote(str(root))}", f"title NEXUS - {title}", "echo."]
    last = len(plan.steps) - 1
    for index, step in enumerate(plan.steps):
        quoted = " ".join(_bat_quote(a) for a in step.args)
        lines.append(f"echo [{step.name}]")
        lines.append(quoted)
        if index < last:
            lines.append("if errorlevel 1 goto failed")
        else:
            lines += ["set NEXUS_CODE=%errorlevel%", "echo.", "echo [Finished with exit code %NEXUS_CODE%]", "goto end"]
    lines += [":failed", "echo.", "echo [Build failed. Fix the errors above, then run again.]", ":end", "echo.", "pause"]
    return "\r\n".join(lines) + "\r\n"


def open_external(plan: Plan, root: pathlib.Path) -> pathlib.Path:
    """Open a new console window that compiles and runs the plan, and stays open at the end."""
    if plan.browser is not None:
        webbrowser.open(plan.browser.as_uri())
        return plan.browser
    if not IS_WINDOWS:
        raise BuildError("Opening a separate terminal window is supported on Windows. Use the inbuilt terminal here.")
    root = root.resolve()
    script = external_script(plan, root)
    directory = root / agent.STATE_DIRNAME / "run"
    directory.mkdir(parents=True, exist_ok=True)
    bat = directory / ("run_" + re.sub(r"[^A-Za-z0-9_.-]", "_", plan.rel) + ".bat")
    bat.write_text(script, encoding="utf-8", newline="")
    subprocess.Popen(["cmd.exe", "/c", str(bat)], cwd=str(root), creationflags=CREATE_NEW_CONSOLE)
    return bat
