def plan_run(root: pathlib.Path, rel: str, cfg: Dict[str, object], for_pipe: bool = True,
             language: Optional[str] = None, internal_notepad: bool = False) -> Plan:
    """Turn a workspace file into compile/run steps, or raise BuildError with advice."""
    root = root.resolve()
    if internal_notepad:
        parts = rel.replace("\\", "/").split("/")
        if (len(parts) != 4 or parts[:2] != [agent.STATE_DIRNAME, "notepad-runs"] or
                not re.fullmatch(r"[0-9a-f]{32}", parts[2]) or
                not re.fullmatch(r"[A-Za-z0-9_.-]{1,100}", parts[3])):
            raise BuildError("That notepad run path is invalid.")
        target = root.joinpath(*parts).resolve()
        internal_root = (root / agent.STATE_DIRNAME / "notepad-runs").resolve()
        try:
            target.relative_to(root)
        except ValueError:
            raise BuildError("That notepad run path is outside the workspace.")
        if internal_root not in target.parents:
            raise BuildError("That notepad run path is outside the workspace state folder.")
        label = target.relative_to(root).as_posix()
    else:
        try:
            target = agent.safe_path(root, rel)
        except ValueError as exc:
            raise BuildError(str(exc))
        label = agent.rel_of(root, target)
    if not target.is_file():
        raise BuildError("That file does not exist.")
    if not agent.is_allowed_file(target) or agent.looks_secret(target.name):
        raise BuildError("This type of file cannot be run from NEXUS.")

    suffix, stem = target.suffix.lower(), target.stem
    detected = detect_language(target)
    if language in (None, "", "auto"):
        language = detected
    elif language not in LANGUAGE_NAMES:
        raise BuildError("Choose a language from the supported language list.")
    run_args = split_cmd(str(cfg.get("run_args", "")))
    flags = split_cmd(str(cfg.get("build_flags", "")))
    build_dir = root / agent.STATE_DIRNAME / "build"
    exe = build_dir / (stem + (".exe" if IS_WINDOWS else ""))
    plan = Plan(rel=label, kind="", language=language or detected)

    custom = str(cfg.get("run_command", "")).strip()
    if custom:
        values = {"{file}": str(target), "{rel}": label, "{dir}": str(target.parent),
                  "{name}": stem, "{root}": str(root)}
        args = split_cmd(custom)
        for key, value in values.items():
            args = [a.replace(key, value) for a in args]
        if not args:
            raise BuildError("run_command is empty.")
        plan.kind = "custom"
        plan.steps = [Step("run", args + run_args)]
        plan.note = "Using your run_command setting."

    elif language == "python":
        plan.kind = "python"
        plan.steps = [Step("run", [sys.executable, "-u", str(target)] + run_args)]

    elif language in ("c", "cpp"):
        is_cpp = language == "cpp"
        compiler = _tool("g++", "clang++") if is_cpp else _tool("gcc", "clang")
        if not compiler:
            raise BuildError(
                ("A C++ compiler (g++)" if is_cpp else "A C compiler (gcc)") +
                " was not found. Install MSYS2 MinGW-w64 and add C:\\msys64\\ucrt64\\bin to PATH "
                "(see the README), then open a new terminal.")
        if not MAIN_RE.search(_read(target)):
            raise BuildError(f"{label} has no main() function, so it cannot be run on its own. "
                             "Open the file that contains main() and press Run.")
        extras = _sibling_sources(target, CPP_SUFFIXES if is_cpp else C_SUFFIXES)
        args = [compiler, "-Wall", "-Wextra", "-g"]
        if is_cpp:
            args.append("-std=c++17")
        args += flags
        if for_pipe:
            args += ["-include", str(write_unbuf_header(build_dir))]
        args += [str(target)] + [str(p) for p in extras] + ["-o", str(exe)]
        if not IS_WINDOWS:
            args.append("-lm")
        plan.kind = "cpp" if is_cpp else "c"
        plan.steps = [Step("compile", args), Step("run", [str(exe)] + run_args)]
        if extras:
            plan.note = "Also compiling: " + ", ".join(p.name for p in extras)

    elif language == "javascript":
        if suffix in (".jsx",):
            transpiler = _tool("tsx")
            if not transpiler:
                raise BuildError("JSX needs the 'tsx' runtime. Install it with npm, then reopen NEXUS.")
            plan.kind = "javascript"
            plan.steps = [Step("run", [transpiler, str(target)] + run_args)]
            plan.display = display_of(plan.steps[0].args, root)
            return plan
        node = _tool("node")
        if not node:
            raise BuildError("Node.js was not found. Install it from nodejs.org.")
        plan.kind = "node"
        plan.steps = [Step("run", [node, str(target)] + run_args)]

    elif language == "typescript":
        runner = _tool("tsx", "ts-node")
        if not runner:
            raise BuildError("TypeScript needs 'tsx' or 'ts-node'. Install one with npm, then reopen NEXUS.")
        plan.kind = "typescript"
        plan.steps = [Step("run", [runner, str(target)] + run_args)]

    elif language == "java":
        javac, java = _tool("javac"), _tool("java")
        if not (javac and java):
            raise BuildError("A JDK (javac and java) was not found on PATH.")
        out = build_dir / "java"
        out.mkdir(parents=True, exist_ok=True)
        plan.kind = "java"
        plan.steps = [Step("compile", [javac, "-d", str(out), str(target)]),
                      Step("run", [java, "-cp", str(out), stem] + run_args)]

    elif language == "csharp":
        compiler = _tool("csc", "mcs")
        if not compiler:
            raise BuildError("A C# compiler (csc or mcs) was not found on PATH.")
        build_dir.mkdir(parents=True, exist_ok=True)
        output = build_dir / (stem + ".exe")
        if pathlib.Path(compiler).name.lower().startswith("mcs"):
            compile_args = [compiler, "-out:" + str(output), str(target)]
        else:
            compile_args = [compiler, "/nologo", "/out:" + str(output), str(target)]
        plan.kind = "csharp"
        plan.steps = [Step("compile", compile_args)]
        if IS_WINDOWS and not pathlib.Path(compiler).name.lower().startswith("mcs"):
            plan.steps.append(Step("run", [str(output)] + run_args))
        else:
            mono = _tool("mono")
            if not mono:
                raise BuildError("Mono is needed to run the compiled C# program on this system.")
            plan.steps.append(Step("run", [mono, str(output)] + run_args))

    elif language == "go":
        go = _tool("go")
        if not go:
            raise BuildError("Go was not found on PATH. Install the Go toolchain and reopen NEXUS.")
        plan.kind = "go"
        plan.steps = [Step("run", [go, "run", str(target)] + run_args)]

    elif language == "rust":
        compiler = _tool("rustc")
        if not compiler:
            raise BuildError("Rust was not found on PATH. Install rustc and reopen NEXUS.")
        build_dir.mkdir(parents=True, exist_ok=True)
        plan.kind = "rust"
        plan.steps = [Step("compile", [compiler, "--edition=2021", str(target), "-o", str(exe)]),
                      Step("run", [str(exe)] + run_args)]

    elif language == "ruby":
        runtime = _tool("ruby")
        if not runtime:
            raise BuildError("Ruby was not found on PATH. Install Ruby and reopen NEXUS.")
        plan.kind = "ruby"
        plan.steps = [Step("run", [runtime, str(target)] + run_args)]

    elif language == "php":
        runtime = _tool("php")
        if not runtime:
            raise BuildError("PHP was not found on PATH. Install PHP and reopen NEXUS.")
        plan.kind = "php"
        plan.steps = [Step("run", [runtime, str(target)] + run_args)]

    elif language == "kotlin":
        compiler, java = _tool("kotlinc"), _tool("java")
        if not compiler or not java:
            raise BuildError("Kotlin needs kotlinc and a Java runtime on PATH.")
        build_dir.mkdir(parents=True, exist_ok=True)
        jar = build_dir / (stem + ".jar")
        plan.kind = "kotlin"
        plan.steps = [Step("compile", [compiler, str(target), "-include-runtime", "-d", str(jar)]),
                      Step("run", [java, "-jar", str(jar)] + run_args)]

    elif language == "swift":
        compiler = _tool("swiftc")
        if not compiler:
            raise BuildError("Swift was not found on PATH. Install the Swift toolchain and reopen NEXUS.")
        build_dir.mkdir(parents=True, exist_ok=True)
        plan.kind = "swift"
        plan.steps = [Step("compile", [compiler, str(target), "-o", str(exe)]),
                      Step("run", [str(exe)] + run_args)]

    elif language == "powershell":
        runtime = _tool("pwsh", "powershell")
        if not runtime:
            raise BuildError("PowerShell was not found on PATH.")
        plan.kind = "powershell"
        plan.steps = [Step("run", [runtime, "-NoProfile", "-File", str(target)] + run_args)]
        plan.note = "PowerShell scripts can change files or system settings. Read them first."

    elif language == "shell":
        bash = _tool("bash")
        if not bash:
            raise BuildError("bash was not found. Install Git for Windows or a Bash environment.")
        plan.kind = "shell"
        plan.steps = [Step("run", [bash, str(target)] + run_args)]
        plan.note = "Shell scripts run commands on your computer. Read them first."

    elif language == "batch":
        if not IS_WINDOWS:
            raise BuildError("Batch files can only be run on Windows.")
        plan.kind = "batch"
        plan.steps = [Step("run", ["cmd.exe", "/c", str(target)] + run_args)]
        plan.note = "Batch files run commands on your computer. Read them first."

    elif language == "lua":
        runtime = _tool("lua")
        if not runtime:
            raise BuildError("Lua was not found on PATH. Install Lua and reopen NEXUS.")
        plan.kind = "lua"
        plan.steps = [Step("run", [runtime, str(target)] + run_args)]

    elif language == "perl":
        runtime = _tool("perl")
        if not runtime:
            raise BuildError("Perl was not found on PATH. Install Perl and reopen NEXUS.")
        plan.kind = "perl"
        plan.steps = [Step("run", [runtime, str(target)] + run_args)]

    elif language == "html":
        plan.kind = "browser"
        plan.browser = target
        plan.display = "open in your web browser"
        return plan

    elif language in ("css", "sql"):
        raise BuildError(f"{LANGUAGE_NAMES[language]} is identified, but it needs a host application or database to run.")

    else:
        if language:
            raise BuildError(f"NEXUS does not yet have a built-in runner for {LANGUAGE_NAMES.get(language, language)}.")
        raise BuildError("NEXUS could not identify this file's language. Choose one and it will use an installed toolchain automatically.")

    plan.display = "  &&  ".join(display_of(s.args, root) for s in plan.steps)
    return plan


def pick_runnable(root: pathlib.Path, rels: Sequence[str], cfg: Dict[str, object]) -> Optional[str]:
    """From the files just changed, choose the one most likely meant to be run."""
    ordered = sorted(reversed(list(rels)),
                     key=lambda r: 0 if pathlib.PurePosixPath(r).stem.lower() in PREFERRED_STEMS else 1)
    for rel in ordered:
        try:
            plan_run(root, rel, cfg)
        except BuildError:
            continue
        return rel
    return None


