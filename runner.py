# Makes stdout/stderr unbuffered in C and C++ programs. When the program's output goes
# to a pipe (our inbuilt terminal) C normally buffers it, so a prompt such as
# printf("Name: ") would not appear until the program ends. The constructor runs
# before main(). Only used for the inbuilt terminal; a real console does not need it.
UNBUF_HEADER = """/* Generated by NEXUS. Not part of your project. */
#include <stdio.h>
__attribute__((constructor)) static void nexus_unbuffer_stdio(void) {
    setvbuf(stdout, NULL, _IONBF, 0);
    setvbuf(stderr, NULL, _IONBF, 0);
}
"""


class BuildError(Exception):
    """A problem the person can act on (missing compiler, nothing to run, ...)."""


@dataclass
class Step:
    name: str                       # "compile" or "run"
    args: List[str]


@dataclass
class Plan:
    rel: str
    kind: str                       # python, c, cpp, node, java, batch, shell, go, custom, browser
    steps: List[Step] = field(default_factory=list)
    display: str = ""
    note: str = ""
    browser: Optional[pathlib.Path] = None
    language: Optional[str] = None
    env: Dict[str, str] = field(default_factory=dict)


