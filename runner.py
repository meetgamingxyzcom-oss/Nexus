def split_cmd(text: str) -> List[str]:
    """Split a command typed in Settings. Windows paths keep their backslashes."""
    text = (text or "").strip()
    if not text:
        return []
    try:
        parts = shlex.split(text, posix=not IS_WINDOWS)
    except ValueError as exc:
        raise BuildError(f"Could not read the command '{text}': {exc}")
    if IS_WINDOWS:
        parts = [p[1:-1] if len(p) >= 2 and p[0] == p[-1] and p[0] in "\"'" else p for p in parts]
    return parts


def display_of(args: Sequence[str], root: pathlib.Path) -> str:
    """A readable one-line version of a command, with the workspace shortened to '.'."""
    text = subprocess.list2cmdline(list(args)) if IS_WINDOWS else shlex.join(list(args))
    prefix = str(root.resolve())
    return text.replace(prefix + os.sep, "." + os.sep).replace(prefix, ".")


def child_env() -> Dict[str, str]:
    env = os.environ.copy()
    env.update({"PYTHONUNBUFFERED": "1", "PYTHONIOENCODING": "utf-8", "PYTHONUTF8": "1"})
    return env


def _tool(*names: str) -> Optional[str]:
    for name in names:
        found = shutil.which(name)
        if found:
            return found
    return None


def _read(path: pathlib.Path, limit: int = 400_000) -> str:
    try:
        return path.read_bytes()[:limit].decode("utf-8", errors="replace")
    except OSError:
        return ""


def _sibling_sources(target: pathlib.Path, suffixes: set) -> List[pathlib.Path]:
    """Other source files in the same folder that do not define main(): helpers to link in."""
    found: List[pathlib.Path] = []
    try:
        names = sorted(target.parent.iterdir())
    except OSError:
        return found
    for path in names:
        if path == target or not path.is_file() or path.suffix.lower() not in suffixes:
            continue
        try:
            if path.stat().st_size > 200_000:
                continue
        except OSError:
            continue
        if MAIN_RE.search(_read(path)):
            continue
        found.append(path)
        if len(found) >= MAX_SIBLING_SOURCES:
            break
    return found


def write_unbuf_header(build_dir: pathlib.Path) -> pathlib.Path:
    build_dir.mkdir(parents=True, exist_ok=True)
    header = build_dir / "nexus_unbuf.h"
    if not header.exists() or header.read_text(encoding="utf-8") != UNBUF_HEADER:
        header.write_text(UNBUF_HEADER, encoding="utf-8")
    return header


def detect_language(target: pathlib.Path) -> Optional[str]:
    """Detect a source language from its suffix, then sniff plain text when needed."""
    suffix = target.suffix.lower()
    known = LANGUAGE_BY_SUFFIX.get(suffix)
    if suffix == ".h" and re.search(r"#\s*include\s*[<\"](?:iostream|string|vector)", _read(target, 24_000)):
        return "cpp"
    if known:
        return known
    if suffix not in ("", ".txt"):
        return None
    source = _read(target, 24_000).lstrip("\ufeff \t\r\n")
    first_line = source.splitlines()[0] if source else ""
    if first_line.startswith("#!"):
        shebang = first_line.lower()
        for marker, language in (("python", "python"), ("bash", "shell"), ("ruby", "ruby"), ("perl", "perl")):
            if marker in shebang:
                return language
    checks = (
        ("rust", r"\bfn\s+main\s*\("),
        ("go", r"(?m)^\s*package\s+main\b"),
        ("cpp", r"#\s*include\s*[<\"](?:iostream|string|vector)"),
        ("c", r"#\s*include\s*[<\"](?:stdio|stdlib)\.h"),
        ("csharp", r"(?m)^\s*using\s+System\s*;|\bConsole\.WriteLine\s*\("),
        ("kotlin", r"\bfun\s+main\s*\("),
        ("swift", r"(?m)^\s*import\s+Foundation\b"),
        ("python", r"(?m)^\s*(?:def\s+\w+|from\s+\w+\s+import\s+|import\s+\w+)|\bprint\s*\("),
        ("java", r"\bpublic\s+(?:static\s+)?class\s+\w+"),
        ("typescript", r"(?m)^\s*(?:interface|type)\s+\w+"),
        ("javascript", r"\b(?:const|let|var)\s+\w+\s*=|\bconsole\.log\s*\(|\bfunction\s+\w+\s*\("),
        ("php", r"<\?php"),
        ("html", r"(?i)<!doctype\s+html|<html\b|<body\b"),
        ("ruby", r"(?m)^\s*(?:puts\s+|def\s+\w+|require\s+['\"]\w+)"),
    )
    for language, pattern in checks:
        if re.search(pattern, source):
            return language
    return None


