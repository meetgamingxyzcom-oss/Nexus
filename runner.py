# -*- coding: utf-8 -*-
"""
NEXUS runner
============

Compiles and runs the user's code. Used by:

  * gui.py    - the inbuilt terminal panel (output streamed to the browser)
  * agent.py  - the /run command and the optional "run after changes" setting
  * the "Open in my terminal" button (a real Windows console window)

Design rules
------------
* Running code is ALWAYS started by the person, from a button, a command, or a
  setting they switched on themselves. The language model can never start a
  program: it has no way to call anything in this module.
* No shell is involved when output is captured: commands are argument lists
  (subprocess with shell=False), so file names cannot inject commands.
* Everything is built from templates below, or from the `run_command` setting
  that the user typed. Nothing comes from model output.
* Build products go to <workspace>/.nexus/build (which the agent never reads
  or edits).

Standard library only.
"""

